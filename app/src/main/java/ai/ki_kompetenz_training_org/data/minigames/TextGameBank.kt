        promptDe = textDe, promptEn = textEn,
        optionsDe = listOf("KI", "Mensch"),
        optionsEn = listOf("AI", "Human"),
        correctIndex = if (isAi) 0 else 1,
        explanationDe = explanationDe, explanationEn = explanationEn,
